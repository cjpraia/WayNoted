const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const os = require('node:os')
const path = require('node:path')
const { prepareClipperInstall } = require('../electron/clipper-install.cjs')

async function setup(t) {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'waynoted-clipper-install-'))
  t.after(() => fs.rm(root, { recursive: true, force: true }))
  const source = path.join(root, 'bundled')
  const profile = path.join(root, 'profile')
  await fs.mkdir(path.join(source, 'icons'), { recursive: true })
  await fs.mkdir(profile)
  const manifest = version => fs.writeFile(path.join(source, 'manifest.json'), JSON.stringify({ manifest_version: 3, version }))
  await manifest('1.0.0')
  await fs.writeFile(path.join(source, 'icons', 'icon.png'), Buffer.from([0, 127, 255]))
  return { source, profile, manifest }
}

test('prepares the extension once, then refreshes the same folder without rewriting unchanged files', async t => {
  const { source, profile, manifest } = await setup(t)
  assert.equal(await prepareClipperInstall(source, profile, { onlyPrepared: true }), null)
  assert.deepEqual(await fs.readdir(profile), [])
  await fs.mkdir(path.join(profile, 'data'))
  await fs.writeFile(path.join(profile, 'data', 'meta.json'), 'workspace')
  const { directory, version } = await prepareClipperInstall(source, profile)
  const icon = path.join(directory, 'icons', 'icon.png')
  assert.equal(version, '1.0.0')
  assert.deepEqual(await fs.readFile(icon), Buffer.from([0, 127, 255]))
  await fs.utimes(icon, 10, 10)
  await fs.writeFile(path.join(directory, 'my-note.txt'), 'retain')
  await manifest('1.1.0')
  const refreshed = await prepareClipperInstall(source, profile, { onlyPrepared: true })
  assert.deepEqual(refreshed, { directory, version: '1.1.0' })
  assert.equal(JSON.parse(await fs.readFile(path.join(directory, 'manifest.json'))).version, '1.1.0')
  assert.equal((await fs.stat(icon)).mtimeMs, 10_000)
  assert.equal(await fs.readFile(path.join(directory, 'my-note.txt'), 'utf8'), 'retain')
  assert.equal(await fs.readFile(path.join(profile, 'data', 'meta.json'), 'utf8'), 'workspace')
})

test('leaves unrelated files alone even when a later bundle ships a resource with the same name', async t => {
  const { source, profile, manifest } = await setup(t)
  const { directory } = await prepareClipperInstall(source, profile)
  await fs.writeFile(path.join(directory, 'new.js'), 'user data')
  await fs.writeFile(path.join(source, 'new.js'), 'bundled resource')
  await manifest('1.1.0')
  await assert.rejects(prepareClipperInstall(source, profile), /conflicting file: new\.js/)
  assert.equal(await fs.readFile(path.join(directory, 'new.js'), 'utf8'), 'user data')
  assert.equal(JSON.parse(await fs.readFile(path.join(directory, 'manifest.json'))).version, '1.0.0')
})
