import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import PRODUCT from '../shared/product.json' with { type: 'json' }
import COMPAT_RECORDS from '../shared/compatibility.json' with { type: 'json' }
const root = fileURLToPath(new URL('..', import.meta.url))
const write = (name, value) => fs.writeFileSync(path.join(root, name), value)
const json = name => JSON.parse(fs.readFileSync(path.join(root, name), 'utf8'))
if (!PRODUCT.name.trim() || !/^[a-z][a-z0-9-]*$/.test(PRODUCT.protocol)) throw new Error('Invalid product registry')
const pkg = json('package.json')
const licenseText = fs.readFileSync(path.join(root, 'LICENSE'), 'utf8')
if (!PRODUCT.license || !PRODUCT.licenseName || !licenseText.includes(PRODUCT.licenseName)) throw new Error('Product license metadata does not match LICENSE')
pkg.name = PRODUCT.packageName; pkg.productName = PRODUCT.name; pkg.description = `${PRODUCT.name} — local workspace for macOS and Windows`
pkg.license = PRODUCT.license
pkg.repository = { type: 'git', url: `git+${PRODUCT.repositoryUrl}.git` }
write('package.json', JSON.stringify(pkg, null, 2) + '\n')
const lock = json('package-lock.json'); lock.name = PRODUCT.packageName
if (lock.packages?.['']) {
  lock.packages[''].name = PRODUCT.packageName
  lock.packages[''].license = PRODUCT.license
}
write('package-lock.json', JSON.stringify(lock, null, 2) + '\n')
const escape = text => text.replace(/&/g, '&amp;').replace(/</g, '&lt;')
for (const name of ['build/app-info', 'native/Info']) {
  let text = fs.readFileSync(path.join(root, name + '.template.plist'), 'utf8').replaceAll('__PRODUCT_NAME__', escape(PRODUCT.name))
  text = text.replaceAll('local.workspace.native', PRODUCT.nativeBundleId)
  write(name + '.plist', text)
}
const manifest = json('clipper/manifest.json'); manifest.name = `${PRODUCT.name} Web Clipper`; manifest.description = `Save pages to your local ${PRODUCT.name} workspace.`
manifest.action.default_title = `Recortar para o ${PRODUCT.name}`
write('clipper/manifest.json', JSON.stringify(manifest, null, 2) + '\n')
write('clipper/LICENSE', licenseText)
write('clipper/identity.js', `// Generated by npm run configure from shared/product.json.\nglobalThis.WorkspaceProduct = Object.freeze({ name: ${JSON.stringify(PRODUCT.name)}, legacyStorageKeys: [atob(${JSON.stringify(COMPAT_RECORDS.clipperStorageKey)})] });\n`)
