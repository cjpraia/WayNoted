export const GLYPHS: GlyphEntry[] = GLYPH_CATEGORIES.flatMap((category) => category.items)
const BY_NAME = new globalThis.Map<string, LucideIcon>(GLYPHS.map((entry) => [entry.name, entry.icon]))

/** Componente lucide de um ícone do catálogo; nomes desconhecidos (dados de versões futuras) caem no documento. */
export function glyphComponent(name: string): LucideIcon | null {
  return BY_NAME.get(name) ?? null
}

const fold = (value: string) => value.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase()

/** Busca bilíngue (PT/EN, sem acentos) por nome e palavras-chave. */
export function searchGlyphs(query: string): GlyphEntry[] {
  const terms = fold(query).trim().split(/\s+/).filter(Boolean)
  if (!terms.length) return GLYPHS
  return GLYPHS.filter((entry) => {
    const hay = fold(`${entry.name.replace(/-/g, ' ')} ${entry.pt} ${entry.en}`)
    return terms.every((term) => hay.includes(term))
  })
}
